# 15. Monotonicity utilities
# ============================================================

def monotonicity_stats(values):
    values = np.asarray(values).reshape(-1)

    if len(values) < 2:
        return {
            "violations": 0,
            "transitions": 0,
            "violation_rate_percent": 0.0,
            "monotonicity_score_percent": 100.0,
            "total_upward_movement": 0.0,
            "max_upward_jump": 0.0,
        }

    diffs = np.diff(values)
    upward = diffs > 0

    violations = int(upward.sum())
    transitions = len(diffs)

    return {
        "violations": violations,
        "transitions": transitions,
        "violation_rate_percent": 100 * violations / transitions,
        "monotonicity_score_percent": 100 * (1 - violations / transitions),
        "total_upward_movement": float(diffs[upward].sum()) if upward.any() else 0.0,
        "max_upward_jump": float(diffs[upward].max()) if upward.any() else 0.0,
    }

