md(r"""
# 9. Guarded PI-GLSTM

The proposed model uses a recurrent representation followed by a degradation head.

The degradation increment is constrained to be non-negative:

\[
\Delta d_t = \operatorname{Softplus}(z_t)
\]

and cumulative degradation is:

\[
D_t = \sum_{k=1}^{t}\Delta d_k
\]

The guarded SoH trajectory is then:

\[
\widehat{SoH}_t =
SoH_{\mathrm{init}} - \alpha D_t
\]

where `alpha` is a learned positive scale.

This architectural guard makes the predicted degradation trajectory non-increasing **within each input sequence**.

The RUL head remains a conventional regression head operating on the final recurrent representation.
""")

code(r"""
# ============================================================
# 9. Guarded PI-GLSTM
# ============================================================

class PIGLSTM(nn.Module):
    def __init__(
        self,
        input_size=INPUT_SIZE,
        hidden_size=HIDDEN_SIZE,
        dropout=DROPOUT,
        dense_size=DENSE_SIZE,
        output_size=OUTPUT_SIZE,
        use_guard=True,
    ):
        super().__init__()

        self.use_guard = use_guard

        self.lstm = nn.LSTM(
            input_size=input_size,
            hidden_size=hidden_size,
            batch_first=True,
        )

        self.dropout = nn.Dropout(dropout)

        # Degradation increment head.
        self.degradation_head = nn.Linear(hidden_size, 1)

        # Positive scale for cumulative degradation.
        self.log_alpha = nn.Parameter(torch.tensor(-2.0))

        # RUL regression head.
        self.rul_fc1 = nn.Linear(hidden_size, dense_size)
        self.rul_fc2 = nn.Linear(dense_size, 1)

    def forward(self, x, initial_soh):
        sequence_h, _ = self.lstm(x)
        sequence_h = self.dropout(sequence_h)

        if self.use_guard:
            raw_delta = self.degradation_head(sequence_h)
            delta = torch.nn.functional.softplus(raw_delta)

            alpha = torch.nn.functional.softplus(self.log_alpha)

            cumulative_degradation = torch.cumsum(delta, dim=1)

            soh_sequence = initial_soh.unsqueeze(1) - alpha * cumulative_degradation

            # The final SoH is the value used for the main supervised target.
            soh_pred = soh_sequence[:, -1, 0]
        else:
            # Unguarded ablation: direct SoH prediction.
            final_h = sequence_h[:, -1, :]
            soh_pred = self.rul_fc1(final_h)
            soh_pred = torch.relu(soh_pred)
            soh_pred = self.rul_fc2(soh_pred)[:, 0]
            soh_sequence = soh_pred.unsqueeze(1).repeat(1, x.size(1), 1)

        final_h = sequence_h[:, -1, :]
        rul_hidden = torch.relu(self.rul_fc1(final_h))
        rul_pred = self.rul_fc2(rul_hidden)[:, 0]

        return soh_pred, rul_pred, soh_sequence

piglstm = PIGLSTM(use_guard=True).to(DEVICE)

print(piglstm)
print("Trainable parameters:", sum(p.numel() for p in piglstm.parameters() if p.requires_grad))
""")

md(r"""
## 10. Training utilities

All models are trained against the same scaled SoH/RUL targets.

The PI-GLSTM loss contains:

1. supervised SoH loss,
2. supervised RUL loss,
3. a sequence-level physics/degradation consistency term.

The architectural Softplus guard is the primary monotonicity mechanism. The additional penalty discourages disagreement between the learned cumulative degradation and the observed capacity-derived degradation direction.
""")

code(r"""
# ============================================================
# 10. Training utilities
# ============================================================

MAX_EPOCHS = 150
PATIENCE = 15
LEARNING_RATE = 1e-3

def get_initial_soh(batch_x):
    # capacity is the fourth feature in the original feature vector.
    # It has been scaled, so recover the physical capacity first.
    cap_scaled = batch_x[:, 0, 3].detach().cpu().numpy()
    cap_original = feature_scaler.inverse_transform(
        np.column_stack([
            np.zeros(len(cap_scaled)),
            np.zeros(len(cap_scaled)),
            np.zeros(len(cap_scaled)),
            cap_scaled,
        ])
    )[:, 3]

    initial_soh = cap_original / NOMINAL_CAPACITY
    return torch.tensor(initial_soh, dtype=torch.float32, device=DEVICE)

def inverse_target(y_scaled):
    return target_scaler.inverse_transform(y_scaled)

def train_baseline(model):
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = nn.MSELoss()

    history = {
        "train_loss": [],
        "val_loss": [],
    }

    best_state = None
    best_val = float("inf")
    patience_count = 0

    for epoch in range(1, MAX_EPOCHS + 1):
        model.train()
        train_losses = []

        for xb, yb in train_loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)

            optimizer.zero_grad()
            pred = model(xb)
            loss = criterion(pred, yb)
            loss.backward()
            optimizer.step()

            train_losses.append(loss.item())

        model.eval()
        val_losses = []

        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(DEVICE), yb.to(DEVICE)
                pred = model(xb)
                val_losses.append(criterion(pred, yb).item())

        train_loss = float(np.mean(train_losses))
        val_loss = float(np.mean(val_losses))

        history["train_loss"].append(train_loss)
        history["val_loss"].append(val_loss)

        if val_loss < best_val:
            best_val = val_loss
            best_state = {
                k: v.detach().cpu().clone()
                for k, v in model.state_dict().items()
            }
            patience_count = 0
        else:
            patience_count += 1

        if patience_count >= PATIENCE:
            break

    model.load_state_dict(best_state)
    return history

def train_piglstm(model, physics_weight=0.10):
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = nn.MSELoss()

    history = {
        "train_loss": [],
        "val_loss": [],
        "supervised_loss": [],
        "physics_loss": [],
    }

    best_state = None
    best_val = float("inf")
    patience_count = 0

    for epoch in range(1, MAX_EPOCHS + 1):
        model.train()

        epoch_losses = []
        epoch_supervised = []
        epoch_physics = []

        for xb, yb in train_loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            initial_soh = get_initial_soh(xb)

            optimizer.zero_grad()

            soh_pred, rul_pred, soh_sequence = model(xb, initial_soh)

            supervised_soh = criterion(soh_pred, yb[:, 0])
            supervised_rul = criterion(rul_pred, yb[:, 1])

            # Capacity-derived target degradation at the end of each window.
            target_soh_physical = torch.tensor(
                target_scaler.inverse_transform(
                    yb.detach().cpu().numpy()
                )[:, 0],
                dtype=torch.float32,
                device=DEVICE,
            )

            # Encourage final predicted degradation to agree with observed
            # degradation over the window.
            predicted_final_soh = soh_sequence[:, -1, 0]
            physics_loss = criterion(
                predicted_final_soh,
                target_soh_physical
            )

            loss = supervised_soh + supervised_rul + physics_weight * physics_loss

            loss.backward()
            optimizer.step()

            epoch_losses.append(loss.item())
            epoch_supervised.append(
                (supervised_soh + supervised_rul).item()
            )
            epoch_physics.append(physics_loss.item())

        # Validation loss
        model.eval()
        val_losses = []

        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(DEVICE), yb.to(DEVICE)
                initial_soh = get_initial_soh(xb)

                soh_pred, rul_pred, _ = model(xb, initial_soh)

                val_loss = (
                    criterion(soh_pred, yb[:, 0])
                    + criterion(rul_pred, yb[:, 1])
                )

                val_losses.append(val_loss.item())

        train_loss = float(np.mean(epoch_losses))
        val_loss = float(np.mean(val_losses))

        history["train_loss"].append(train_loss)
        history["val_loss"].append(val_loss)
        history["supervised_loss"].append(float(np.mean(epoch_supervised)))
        history["physics_loss"].append(float(np.mean(epoch_physics)))

        if val_loss < best_val:
            best_val = val_loss
            best_state = {
                k: v.detach().cpu().clone()
                for k, v in model.state_dict().items()
            }
            patience_count = 0
        else:
            patience_count += 1

        if patience_count >= PATIENCE:
            break

    model.load_state_dict(best_state)
    return history
""")

