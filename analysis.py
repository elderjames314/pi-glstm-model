# ============================================================
# 17. Statistical significance
# ============================================================

def paired_significance(y_true, pred_a, pred_b, label):
    err_a = np.abs(y_true - pred_a)
    err_b = np.abs(y_true - pred_b)
    diff = err_a - err_b

    # Shapiro is informative for the assumption, but not treated as a
    # binary substitute for scientific judgment.
    shapiro_stat, shapiro_p = shapiro(diff) if len(diff) <= 5000 else (np.nan, np.nan)

    t_stat, t_p = ttest_rel(err_a, err_b)

    try:
        w_stat, w_p = wilcoxon(
            err_a,
            err_b,
            zero_method="wilcox",
            alternative="two-sided",
        )
    except ValueError:
        w_stat, w_p = np.nan, np.nan

    return {
        "Target": label,
        "Mean baseline absolute error": float(np.mean(err_a)),
        "Mean PI absolute error": float(np.mean(err_b)),
        "Mean paired difference": float(np.mean(diff)),
        "Median paired difference": float(np.median(diff)),
        "Shapiro W": float(shapiro_stat),
        "Shapiro p": float(shapiro_p),
        "Paired t statistic": float(t_stat),
        "Paired t p": float(t_p),
        "Wilcoxon statistic": float(w_stat) if not np.isnan(w_stat) else np.nan,
        "Wilcoxon p": float(w_p) if not np.isnan(w_p) else np.nan,
    }

significance_table = pd.DataFrame([
    paired_significance(
        y_test_original[:, 0],
        baseline_pred[:, 0],
        pi_pred[:, 0],
        "SoH",
    ),
    paired_significance(
        y_test_original[:, 1],
        baseline_pred[:, 1],
        pi_pred[:, 1],
        "RUL",
    ),
])

